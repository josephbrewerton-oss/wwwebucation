/**
 * scripts/build-wasm.js
 * 
 * Compiles static/player/wasm/ast-wasm-engine.wat into:
 * 1. static/player/wasm/ast-wasm-engine.wasm (binary)
 * 2. static/player/wasm/ast-wasm-engine.bin.js (inlined base64)
 * 3. static/player/wasm/ast-3d-engine.wasm & .bin.js (compatibility aliases)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import wabtFactory from 'wabt';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

async function buildWasm() {
  const wabt = await wabtFactory();
  const watPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-wasm-engine.wat');
  const wasmBinaryPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-wasm-engine.wasm');
  const wasmJsPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-wasm-engine.bin.js');

  const legacyWasmPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-3d-engine.wasm');
  const legacyJsPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-3d-engine.bin.js');

  if (!fs.existsSync(watPath)) {
    console.error('WAT file not found at:', watPath);
    process.exit(1);
  }

  const watSource = fs.readFileSync(watPath, 'utf8');
  const parsed = wabt.parseWat(path.basename(watPath), watSource);
  const binary = parsed.toBinary({ log: false, write_debug_names: false }).buffer;

  // 1. Write standalone .wasm binary
  fs.writeFileSync(wasmBinaryPath, Buffer.from(binary));
  fs.writeFileSync(legacyWasmPath, Buffer.from(binary));
  console.log(`[WASM BUILD] Successfully compiled .wasm (${binary.length} bytes) -> ${wasmBinaryPath}`);

  // 2. Write inlined base64 module for instant airgapped execution
  const base64 = Buffer.from(binary).toString('base64');
  const jsContent = `/**
 * static/player/wasm/ast-wasm-engine.bin.js
 * Auto-generated by scripts/build-wasm.js — DO NOT EDIT DIRECTLY.
 * Inlined WebAssembly binary (${binary.length} bytes) for zero-latency, air-gapped execution.
 */
export const AST_WASM_BASE64 = "${base64}";
export const AST_3D_WASM_BASE64 = "${base64}";
export const AST_WASM_BYTE_LENGTH = ${binary.length};

export function getWasmBinaryBytes() {
  if (typeof atob === 'function') {
    const binStr = atob(AST_WASM_BASE64);
    const len = binStr.length;
    const bytes = new Uint8Array(len);
    for (let i = 0; i < len; i++) {
      bytes[i] = binStr.charCodeAt(i);
    }
    return bytes;
  }
  return Buffer.from(AST_WASM_BASE64, 'base64');
}
`;

  fs.writeFileSync(wasmJsPath, jsContent, 'utf8');
  fs.writeFileSync(legacyJsPath, jsContent, 'utf8');
  // 3. Compile Transpiler WASM Kernel
  const transpilerWatPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-transpiler-engine.wat');
  const transpilerWasmPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-transpiler-engine.wasm');
  const transpilerJsPath = path.join(rootDir, 'static', 'player', 'wasm', 'ast-transpiler-engine.bin.js');

  if (fs.existsSync(transpilerWatPath)) {
    const tWatSource = fs.readFileSync(transpilerWatPath, 'utf8');
    const tParsed = wabt.parseWat(path.basename(transpilerWatPath), tWatSource);
    const tBinary = tParsed.toBinary({ log: false, write_debug_names: false }).buffer;
    fs.writeFileSync(transpilerWasmPath, Buffer.from(tBinary));
    console.log(`[WASM BUILD] Successfully compiled transpiler .wasm (${tBinary.length} bytes) -> ${transpilerWasmPath}`);

    const tBase64 = Buffer.from(tBinary).toString('base64');
    const tJsContent = `/**
 * static/player/wasm/ast-transpiler-engine.bin.js
 * Auto-generated by scripts/build-wasm.js — DO NOT EDIT DIRECTLY.
 * Inlined WebAssembly binary (${tBinary.length} bytes) for zero-latency, air-gapped execution.
 */
export const AST_TRANSPILER_WASM_BASE64 = "${tBase64}";
export const AST_TRANSPILER_WASM_BYTE_LENGTH = ${tBinary.length};

export function getTranspilerWasmBinaryBytes() {
  if (typeof atob === 'function') {
    const binStr = atob(AST_TRANSPILER_WASM_BASE64);
    const len = binStr.length;
    const bytes = new Uint8Array(len);
    for (let i = 0; i < len; i++) {
      bytes[i] = binStr.charCodeAt(i);
    }
    return bytes;
  }
  return Buffer.from(AST_TRANSPILER_WASM_BASE64, 'base64');
}
`;
    fs.writeFileSync(transpilerJsPath, tJsContent, 'utf8');
    console.log(`[WASM BUILD] Inlined transpiler base64 bridge written -> ${transpilerJsPath}`);
  }
}

buildWasm().catch((err) => {
  console.error('WASM Build failed:', err);
  process.exit(1);
});
