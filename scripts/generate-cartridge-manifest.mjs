import { readdirSync, readFileSync, existsSync, writeFileSync } from 'node:fs';
import { resolve, extname, basename } from 'node:path';

const BYTECODE_DIR = resolve('./static/player/bytecode');
const CARTRIDGES_DIR = resolve('./static/player/cartridges');
const OUTPUT_FILE = resolve('./static/player/manifest.ast');

// Fallback human-readable title generator from slug
function slugToTitle(slug) {
  return slug
    .split('-')
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

// Scans an associated .ast source file for explicit metadata fields
function extractAstMetadata(id) {
  const astPath = resolve(CARTRIDGES_DIR, `${id}.ast`);
  if (!existsSync(astPath)) {
    return { title: slugToTitle(id), type: "Sim", stage: "PORTAL APPARATUS" };
  }

  const content = readFileSync(astPath, 'utf8');
  
  const getField = (field, fallback) => {
    const match = content.match(new RegExp(`:${field}\\s+"([^"]+)"`));
    return match ? match[1] : fallback;
  };

  return {
    title: getField('title', slugToTitle(id)),
    type: getField('type', 'Sim'),
    stage: getField('stage', 'PORTAL APPARATUS'),
    oakId: getField('oak-id', null)
  };
}

function buildManifest() {
  if (!existsSync(BYTECODE_DIR)) {
    console.error(`Bytecode directory not found: ${BYTECODE_DIR}`);
    process.exit(1);
  }

  // Scan all .astb binaries and sort alphabetically for deterministic git diffs
  const bytecodeFiles = readdirSync(BYTECODE_DIR)
    .filter(file => extname(file) === '.astb')
    .sort();

  const entries = bytecodeFiles.map(file => {
    const id = basename(file, '.astb');
    const meta = extractAstMetadata(id);

    return [
      `    (:cartridge`,
      `      :id "${id}"`,
      `      :type "${meta.type}"`,
      `      :title "${meta.title}"`,
      `      :stage "${meta.stage}"`,
      meta.oakId ? `      :oak-id "${meta.oakId}"` : null,
      `      :bytecode "bytecode/${file}")`
    ].filter(Boolean).join('\n');
  });

  const timestamp = new Date().toISOString().split('T')[0];

  const astOutput = [
    `;; Autogenerated by scripts/generate-cartridge-manifest.mjs`,
    `;; Generated: ${timestamp}`,
    `;; Zero-Alloc Linear WASM Registry`,
    `(:manifest`,
    `  :registry "Cartridge Bytecode Registry"`,
    `  :count ${entries.length}`,
    `  (:cartridges (`,
    entries.join('\n\n'),
    `  ))`,
    `)\n`
  ].join('\n');

  writeFileSync(OUTPUT_FILE, astOutput, 'utf8');
  console.log(`Generated manifest.ast with ${entries.length} cartridges at: ${OUTPUT_FILE}`);
}

buildManifest();
